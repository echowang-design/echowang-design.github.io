window.addEventListener('keydown',e=>{
  if(e.key==='ArrowRight'||e.key.toLowerCase()==='d'){e.preventDefault();move(1,3)}
  if(e.key==='ArrowLeft'||e.key.toLowerCase()==='a'){e.preventDefault();move(-1,3)}
  if(e.code==='Space'){e.preventDefault();jump()}
  if(e.key.toLowerCase()==='e'){
    const nearest=[...document.querySelectorAll('.portal')].map(p=>({el:p,x:parseFloat(getComputedStyle(p).left),d:Math.abs(parseFloat(getComputedStyle(p).left)-playerX)})).sort((a,b)=>a.d-b.d)[0];
    if(nearest && nearest.d<7) openProject(nearest.el.dataset.project); else showToast('MOVE CLOSER TO A PORTAL');
  }
  if(e.key==='Escape')closePanel();
});
document.getElementById('game').addEventListener('touchstart',e=>{touchStartX=e.touches[0].clientX},{passive:true});
document.getElementById('game').addEventListener('touchmove',e=>{
  if(touchStartX===null)return;
  const dx=e.touches[0].clientX-touchStartX;
  if(Math.abs(dx)>8){targetX=Math.max(5,Math.min(96,targetX-dx*.018));touchStartX=e.touches[0].clientX}
},{passive:true});
document.getElementById('game').addEventListener('touchend',()=>touchStartX=null,{passive:true});
updateWorld();
