let playerX=7, targetX=7, jumping=false, touchStartX=null, autoTimer=null;

function enterWorld(){
  intro.classList.add('is-hidden');
  game.classList.add('is-active');
  showToast('ECHO WORLD · MOVE TO EXPLORE');
}
function move(dir, amount=2.3){
  targetX = Math.max(5, Math.min(96, targetX + dir*amount));
  avatarImg.style.transform = `translateX(-50%) scaleX(${dir<0?-1:1})`;
}
function updateWorld(){
  playerX += (targetX-playerX)*0.18;
  avatar.style.left = playerX+'%';
  const vw=window.innerWidth, worldW=layer.scrollWidth || (vw*5);
  const maxTranslate=Math.max(0,worldW-vw);
  const t=(playerX-5)/91;
  layer.style.transform=`translateX(${-maxTranslate*t}px)`;
  progressBar.style.width=Math.max(0,Math.min(100,(playerX-5)/91*100))+'%';
  requestAnimationFrame(updateWorld);
}
function jump(){
  if(jumping) return;
  jumping=true;
  avatar.animate([{transform:'translateX(-50%) translateY(0)'},{transform:'translateX(-50%) translateY(-95px)'},{transform:'translateX(-50%) translateY(0)'}],{duration:620,easing:'cubic-bezier(.2,.8,.2,1)'});
  setTimeout(()=>jumping=false,620);
}
function showToast(msg){
  toast.textContent=msg; toast.classList.add('show');
  clearTimeout(autoTimer); autoTimer=setTimeout(()=>toast.classList.remove('show'),1800);
}
